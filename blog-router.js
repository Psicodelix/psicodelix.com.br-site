// Função principal de roteamento
function handleHashChange() {
    const hash = window.location.hash;
    if (hash.startsWith('#/blog/')) {
        const slug = hash.substring(7);
        renderBlogPost(slug);
    } else {
        renderHomePage();
    }
}

